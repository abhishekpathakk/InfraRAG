#!/usr/bin/env python3
"""
InfraRAG Real Local Neural Embedding Evaluation Suite.

Evaluates dense retrieval and BM25 hybrid ranking over real neural vectors generated by:
- Model: BAAI/bge-small-en-v1.5
- Commit SHA: 5c38ec7c405ec4b44b94cc5a9bb96e735b38267a
- Quantized ONNX Engine: Qdrant/bge-small-en-v1.5-onnx-Q (aa8f8b060edb00e03bfdd08813a2949946c8ba55)
- Dimension: 384
- Refusal Threshold: Empirically calibrated strictly on separate dev set (evaluation/dev_calibration_dataset.json)

Reports:
1. Dense-Only vs. Hybrid (Dense + BM25) for:
   - Primary Golden Benchmark (Reference / Seen)
   - Tagged Held-Out v1 (Reference / Seen)
   - Blind Held-Out v2 (Unseen)
   - Blind Held-Out v3 (Unseen)
2. Metrics: Top-1 Hit-Rate, Top-5 Hit-Rate, MRR, Out-of-Domain Refusal Accuracy.
"""

import json
import logging
import sys
from pathlib import Path
from typing import Any

ROOT_DIR = Path(__file__).resolve().parent.parent
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

from rich.console import Console
from rich.table import Table

from src.chain import RAGChain
from src.config import settings
from src.embeddings import LocalFastEmbedProvider
from src.vector_store import FAISSVectorStore

console = Console()
logger = logging.getLogger("evaluate_local")

INDEX_DIR = settings.BASE_DIR / "index_cache" / "local_bge_small"
CALIBRATION_REPORT_PATH = settings.BASE_DIR / "evaluation" / "dev_calibration_report.json"


def evaluate_dataset(
    chain: RAGChain,
    dataset_path: Path,
    title: str,
    hybrid: bool = True,
) -> dict[str, Any]:
    with open(dataset_path, "r", encoding="utf-8") as f:
        items = json.load(f)

    results = []
    in_domain_total = 0
    top1_hits = 0
    top5_hits = 0
    mrr_sum = 0.0
    in_domain_grounded = 0

    out_domain_total = 0
    out_domain_refusals = 0

    total_latency_ms = 0.0
    total_retrieval_ms = 0.0

    for item in items:
        q_id = item["id"]
        question = item.get("question") or item.get("query", "")
        is_in_domain = item["is_in_domain"]
        expected_src = item.get("expected_source") or item.get("target_source_file")
        expected_kws = item.get("expected_keywords") or item.get("expected_answer_keywords", [])

        response = chain.answer_question(question, hybrid=hybrid)
        total_latency_ms += response.latency_ms
        total_retrieval_ms += response.retrieval_latency_ms

        hit_rank = 0
        if is_in_domain:
            in_domain_total += 1
            retrieved_sources = [f"{c.source_file} {c.path}" for c in response.retrieved_chunks]

            for rank_idx, src in enumerate(retrieved_sources, start=1):
                is_match = False
                if isinstance(expected_src, list):
                    is_match = any(s.lower() in src.lower() for s in expected_src)
                elif expected_src:
                    is_match = expected_src.lower() in src.lower()

                if is_match:
                    hit_rank = rank_idx
                    break

            if hit_rank == 1:
                top1_hits += 1
                top5_hits += 1
                mrr_sum += 1.0
            elif hit_rank > 1:
                top5_hits += 1
                mrr_sum += 1.0 / hit_rank

            has_kws = any(kw.lower() in response.answer.lower() for kw in expected_kws)
            has_cits = len(response.citations) > 0
            if has_kws and has_cits:
                in_domain_grounded += 1
        else:
            out_domain_total += 1
            if "I don't know based on the provided runbooks." in response.answer:
                out_domain_refusals += 1

        results.append({
            "id": q_id,
            "question": question,
            "is_in_domain": is_in_domain,
            "retrieval_rank": hit_rank if hit_rank > 0 else None,
            "answer": response.answer,
            "latency_ms": response.latency_ms,
        })

    top1_rate = (top1_hits / in_domain_total * 100.0) if in_domain_total else 100.0
    top5_rate = (top5_hits / in_domain_total * 100.0) if in_domain_total else 100.0
    mrr = (mrr_sum / in_domain_total) if in_domain_total else 1.0
    grounded_rate = (in_domain_grounded / in_domain_total * 100.0) if in_domain_total else 100.0
    refusal_rate = (out_domain_refusals / out_domain_total * 100.0) if out_domain_total else 100.0
    avg_latency = total_latency_ms / len(items)
    avg_retrieval = total_retrieval_ms / len(items)

    return {
        "dataset": str(dataset_path.name),
        "title": title,
        "mode": "hybrid" if hybrid else "dense_only",
        "total_queries": len(items),
        "in_domain_total": in_domain_total,
        "out_domain_total": out_domain_total,
        "top1_hit_rate_pct": round(top1_rate, 2),
        "top5_hit_rate_pct": round(top5_rate, 2),
        "mrr": round(mrr, 3),
        "in_domain_grounded_pct": round(grounded_rate, 2),
        "out_domain_refusal_pct": round(refusal_rate, 2),
        "avg_latency_ms": round(avg_latency, 2),
        "avg_retrieval_ms": round(avg_retrieval, 2),
    }


def run_local_evaluation() -> dict:
    if not INDEX_DIR.exists():
        raise FileNotFoundError(f"Index directory {INDEX_DIR} does not exist. Run scripts/build_local_index.py first.")

    # Read calibrated threshold from separate dev set
    refusal_threshold = 0.50
    if CALIBRATION_REPORT_PATH.exists():
        with open(CALIBRATION_REPORT_PATH, "r", encoding="utf-8") as f:
            dev_meta = json.load(f)
            refusal_threshold = float(dev_meta.get("frozen_refusal_threshold", 0.50))
    console.print(f"[bold cyan]Using Frozen Refusal Threshold:[/bold cyan] [bold yellow]{refusal_threshold:.2f}[/bold yellow] (from separate dev set)")

    provider = LocalFastEmbedProvider()
    store = FAISSVectorStore(dimension=provider.dimension)
    store.load_local(INDEX_DIR, expected_model_id=f"fastembed:{provider.model_name}@{provider.revision}")

    chain = RAGChain(
        embedding_provider=provider,
        vector_store=store,
        min_relevance_threshold=refusal_threshold,
    )

    suites = [
        ("Golden Benchmark (Burned/Seen)", settings.BASE_DIR / "evaluation" / "golden_dataset.json"),
        ("Tagged Held-Out v1 (Burned/Seen)", settings.BASE_DIR / "evaluation" / "held_out_dataset.json"),
        ("Blind Held-Out v2 (Unseen)", settings.BASE_DIR / "evaluation" / "held_out_dataset_v2.json"),
        ("Blind Held-Out v3 (Unseen)", settings.BASE_DIR / "evaluation" / "held_out_dataset_v3.json"),
        ("Blind Held-Out v4 (Unseen, 65 Questions)", settings.BASE_DIR / "evaluation" / "held_out_dataset_v4.json"),
    ]

    dense_results = {}
    hybrid_results = {}

    console.print("\n[bold magenta]Evaluating All 4 Suites under Dense-Only and Hybrid Modes...[/bold magenta]\n")
    for name, path in suites:
        if not path.exists():
            continue
        # 1. Dense Only
        dense_res = evaluate_dataset(chain=chain, dataset_path=path, title=name, hybrid=False)
        dense_results[name] = dense_res

        # 2. Hybrid (Dense + BM25)
        hybrid_res = evaluate_dataset(chain=chain, dataset_path=path, title=name, hybrid=True)
        hybrid_results[name] = hybrid_res

    # Print Comparative Table: Dense-Only vs. Hybrid
    table = Table(
        title="⚡ BAAI/bge-small-en-v1.5 Dense-Only vs. Hybrid Retrieval Comparison",
        show_header=True,
        header_style="bold green",
    )
    table.add_column("Evaluation Suite", style="bold")
    table.add_column("Dense Top-1", justify="center")
    table.add_column("Hybrid Top-1", justify="center", style="bold yellow")
    table.add_column("Dense Top-5", justify="center")
    table.add_column("Hybrid Top-5", justify="center", style="bold yellow")
    table.add_column("BM25 Delta", justify="center")
    table.add_column("Dense MRR", justify="center")
    table.add_column("Hybrid MRR", justify="center", style="bold yellow")
    table.add_column("Refusal Acc (Dense / Hybrid)", justify="center")

    for name, _ in suites:
        d = dense_results.get(name)
        h = hybrid_results.get(name)
        if d and h:
            delta = h["top1_hit_rate_pct"] - d["top1_hit_rate_pct"]
            delta_str = f"+{delta:.1f}%" if delta > 0 else f"{delta:.1f}%"
            table.add_row(
                name,
                f"{d['top1_hit_rate_pct']}%",
                f"{h['top1_hit_rate_pct']}%",
                f"{d['top5_hit_rate_pct']}%",
                f"{h['top5_hit_rate_pct']}%",
                f"[green]{delta_str}[/green]" if delta > 0 else f"[dim]{delta_str}[/dim]",
                f"{d['mrr']:.3f}",
                f"{h['mrr']:.3f}",
                f"{d['out_domain_refusal_pct']}% / {h['out_domain_refusal_pct']}%",
            )

    console.print(table)

    report_path = settings.BASE_DIR / "evaluation" / "eval_report_local.json"
    full_report = {
        "model_name": provider.model_name,
        "canonical_commit_sha": provider.revision,
        "onnx_distribution": "Qdrant/bge-small-en-v1.5-onnx-Q (aa8f8b060edb00e03bfdd08813a2949946c8ba55)",
        "vector_dimension": provider.dimension,
        "frozen_refusal_threshold": refusal_threshold,
        "dense_only_evaluations": dense_results,
        "hybrid_evaluations": hybrid_results,
    }

    with open(report_path, "w", encoding="utf-8") as f:
        json.dump(full_report, f, indent=2)

    console.print(f"\n[bold green]Local evaluation report saved to {report_path}[/bold green]\n")
    return full_report


if __name__ == "__main__":
    run_local_evaluation()

